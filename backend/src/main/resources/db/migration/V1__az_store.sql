CREATE TABLE shop_user (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE, phone VARCHAR(24) NOT NULL DEFAULT '', password_hash VARCHAR(200) NOT NULL, role VARCHAR(20) NOT NULL DEFAULT 'customer' CHECK(role IN ('customer','admin')));
CREATE TABLE category (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100) NOT NULL, slug VARCHAR(120) NOT NULL UNIQUE, description VARCHAR(2000) NOT NULL DEFAULT '', visible BOOLEAN NOT NULL DEFAULT TRUE);
CREATE TABLE product (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(160) NOT NULL, sku VARCHAR(80) NOT NULL UNIQUE, description VARCHAR(8000) NOT NULL DEFAULT '', category_id BIGINT NOT NULL REFERENCES category(id), price BIGINT NOT NULL CHECK(price>=0), stock INTEGER NOT NULL CHECK(stock>=0), status VARCHAR(20) NOT NULL CHECK(status IN ('draft','published')), image VARCHAR(300) NOT NULL, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE INDEX product_category ON product(category_id,status);
CREATE TABLE shop_order (id VARCHAR(40) PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES shop_user(id), customer_name VARCHAR(100) NOT NULL, phone VARCHAR(24) NOT NULL, note VARCHAR(1000) NOT NULL DEFAULT '', total BIGINT NOT NULL CHECK(total>=0), status VARCHAR(30) NOT NULL DEFAULT 'awaiting_confirmation' CHECK(status IN ('awaiting_confirmation','confirmed','preparing','shipped','delivered','cancelled')), channel VARCHAR(20) NOT NULL DEFAULT 'whatsapp', payment_status VARCHAR(20) NOT NULL DEFAULT 'not_requested', idempotency_key VARCHAR(36) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE(user_id,idempotency_key));
CREATE TABLE order_item (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id VARCHAR(40) NOT NULL REFERENCES shop_order(id), product_id BIGINT NOT NULL REFERENCES product(id), name VARCHAR(160) NOT NULL, sku VARCHAR(80) NOT NULL, quantity INTEGER NOT NULL CHECK(quantity>0), unit_price BIGINT NOT NULL CHECK(unit_price>=0));
CREATE INDEX order_owner ON shop_order(user_id,created_at);
